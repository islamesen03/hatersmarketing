"""Build the transparent motion layers for the four signature scenes.

Usage (offline authoring step, see README.md in this folder):
    python -I scripts/motion-layers/extract.py [--scene heart-box|cards|owl|pawns ...] [--review DIR]

Writes:
    public/images/motion/<scene>/<layer>.png   trimmed, lossless RGBA layers served by next/image
    assets/motion-src/manifest.json            artboards, layer offsets, pivots, anchors, notes
    src/content/motion-assets.ts               typed manifest consumed by the scene components
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import OUT_DIR, ROOT, SRC_DIR, Layer, SceneManifest, save_png, trim  # noqa: E402

SCENES = ["heart-box", "cards", "owl", "pawns"]
Z_ORDER = {
    "heart-box": {"box-rear": 1, "balloon": 2, "box-front": 3},
    "cards": {"stack-body": 1, "top-card": 2, "red-card": 3},
    "owl": {"owl": 1, "lid-viewer-left": 2, "lid-viewer-right": 3},
}
ROLES = {
    "heart-box": {"box-rear": "static", "balloon": "scroll", "box-front": "static"},
    "cards": {"stack-body": "static", "top-card": "scroll", "red-card": "scroll"},
    "owl": {"owl": "scroll", "lid-viewer-left": "wink", "lid-viewer-right": "wink"},
}


def export(manifest: SceneManifest, layers: dict, pivots: dict | None = None, roles: dict | None = None, z: dict | None = None):
    pivots = pivots or {}
    roles = roles or ROLES.get(manifest.id, {})
    z = z or Z_ORDER.get(manifest.id, {})
    out_dir = OUT_DIR / manifest.id
    manifest.layers = []
    for i, (name, img) in enumerate(layers.items()):
        cropped, x, y = trim(img, pad=2)
        size = save_png(cropped, out_dir / f"{name}.png")
        pivot = pivots.get(name)
        if pivot is not None:
            # pivot as a fraction of the layer box, so CSS transform-origin can use percentages
            pivot = [round((pivot[0] - x) / cropped.shape[1], 5), round((pivot[1] - y) / cropped.shape[0], 5)]
        manifest.layers.append(
            Layer(
                name=name,
                file=f"/images/motion/{manifest.id}/{name}.png",
                x=x,
                y=y,
                width=int(cropped.shape[1]),
                height=int(cropped.shape[0]),
                z=z.get(name, i + 1),
                role=roles.get(name, "static"),
                bytes=size,
                pivot=pivot,
            )
        )
    return manifest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scene", action="append", choices=SCENES)
    ap.add_argument("--review", type=Path, default=None)
    args = ap.parse_args()
    wanted = args.scene or SCENES

    existing = {}
    mpath = SRC_DIR / "manifest.json"
    if mpath.exists():
        for s in json.loads(mpath.read_text(encoding="utf-8"))["scenes"]:
            existing[s["id"]] = s

    results = []
    for scene in SCENES:
        if scene not in wanted:
            if scene in existing:
                results.append(existing[scene])
            continue
        if scene == "heart-box":
            import heart

            m, layers = heart.build(args.review)
            results.append(export(m, layers, pivots={"balloon": heart.PIVOT}))
        elif scene == "cards":
            import cards

            m, layers = cards.build(args.review)
            results.append(export(m, layers, pivots=cards.PIVOTS))
        elif scene == "owl":
            import owl

            m, layers = owl.build(args.review)
            results.append(export(m, layers, pivots={}))
        elif scene == "pawns":
            import pawns

            m, layers = pawns.build(args.review)
            results.append(export(m, layers, pivots=pawns.PIVOTS, roles=pawns.ROLES, z=pawns.Z))
        print("scene", scene, "ok")

    norm = [r.to_json() if isinstance(r, SceneManifest) else r for r in results]
    mpath.parent.mkdir(parents=True, exist_ok=True)
    mpath.write_text(json.dumps({"version": 1, "scenes": norm}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_ts(norm)
    for s in norm:
        total = sum(layer["bytes"] for layer in s["layers"])
        print(f"  {s['id']}: {len(s['layers'])} layers, {total / 1024:.0f} KB png total")


def write_ts(scenes):
    lines = [
        "// GENERATED by scripts/motion-layers/extract.py - do not edit by hand.",
        "// Artboard geometry, layer offsets and pivots for the four signature scenes.",
        "",
        'import type { SceneId } from "./types";',
        "",
        "export type MotionLayer = {",
        "  name: string;",
        "  file: string;",
        "  /** Offset of the trimmed layer inside the artboard, in artboard pixels. */",
        "  x: number;",
        "  y: number;",
        "  width: number;",
        "  height: number;",
        "  z: number;",
        '  role: "static" | "scroll" | "wink";',
        "  /** transform-origin as a fraction of the layer box, when the layer rotates. */",
        "  pivot?: [number, number];",
        "};",
        "",
        "export type MotionScene = {",
        "  id: SceneId;",
        "  artboard: { width: number; height: number };",
        "  layers: MotionLayer[];",
        "  anchors: Record<string, unknown>;",
        "};",
        "",
        "export const motionScenes: Partial<Record<SceneId, MotionScene>> = {",
    ]
    for s in scenes:
        lines.append(f'  "{s["id"]}": {{')
        lines.append(f'    id: "{s["id"]}",')
        lines.append(f'    artboard: {{ width: {s["artboard"]["width"]}, height: {s["artboard"]["height"]} }},')
        lines.append("    layers: [")
        for layer in s["layers"]:
            pivot = f", pivot: [{layer['pivot'][0]}, {layer['pivot'][1]}]" if layer.get("pivot") else ""
            lines.append(
                "      { "
                f'name: "{layer["name"]}", file: "{layer["file"]}", x: {layer["x"]}, y: {layer["y"]}, '
                f'width: {layer["width"]}, height: {layer["height"]}, z: {layer["z"]}, role: "{layer["role"]}"{pivot}'
                " },"
            )
        lines.append("    ],")
        lines.append(f"    anchors: {json.dumps(s['anchors'], ensure_ascii=False)},")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    (ROOT / "src" / "content" / "motion-assets.ts").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
